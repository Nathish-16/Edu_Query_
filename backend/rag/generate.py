def verify_and_clean_citations(answer: str, citations_list: List[int], retrieved_chunks: List[Dict[str, Any]]) -> Dict[str, Any]:
    """
    Validates the citations returned in the structured JSON against the retrieved chunks.
    Constructs a list of verified unique references. Also searches the answer text
    for any inline citation brackets (e.g., [1]) to keep them synchronized.
    """
    verified_sources = []
    seen_source_ids = set()
    valid_indices = set()
    num_chunks = len(retrieved_chunks)
    
    # 1. Parse valid indices from both the JSON citations array and inline text brackets
    inline_citations = [int(idx) for idx in re.findall(r'\[(\d+)\]', answer)]
    combined_indices = set(citations_list + inline_citations)
    
    for idx in combined_indices:
        if 1 <= idx <= num_chunks:
            valid_indices.add(idx)
            chunk = retrieved_chunks[idx - 1]
            meta = chunk.get("metadata", {})
            source_name = meta.get("source", "Unknown Document")
            
            ref_label = ""
            if meta.get("type") == "pdf":
                ref_label = f"Page {meta.get('page_number', 'unknown')}"
            elif meta.get("type") == "pptx":
                ref_label = f"Slide {meta.get('slide_number', 'unknown')}"
            else:
                ref_label = "Source"
                
            source_id = f"{source_name}_{ref_label}"
            
            if source_id not in seen_source_ids:
                seen_source_ids.add(source_id)
                verified_sources.append({
                    "id": source_id,
                    "document": source_name,
                    "reference": ref_label,
                    "type": meta.get("type", "pdf"),
                    "title": meta.get("title", ""),
                    "similarity": chunk.get("similarity", 1.0)
                })

    # Clean the answer text: remove hallucinated inline citations
    def clean_match(match):
        idx_str = match.group(1)
        idx = int(idx_str)
        if idx in valid_indices:
            return f"[{idx}]"
        return ""

    citation_pattern = re.compile(r'\[(\d+)\]')
    cleaned_answer = citation_pattern.sub(clean_match, answer)
    cleaned_answer = re.sub(r'\s+([\.!?])', r'\1', cleaned_answer)
    cleaned_answer = re.sub(r'\[\]', '', cleaned_answer).strip()

    # Fallback to map all chunks if no citations were generated by LLM
    if not verified_sources and retrieved_chunks:
        for idx, chunk in enumerate(retrieved_chunks, start=1):
            meta = chunk.get("metadata", {})
            source_name = meta.get("source", "Unknown Document")
            ref_label = f"Page {meta.get('page_number', 'unknown')}" if meta.get('type') == 'pdf' else f"Slide {meta.get('slide_number', 'unknown')}"
            source_id = f"{source_name}_{ref_label}"
            
            if source_id not in seen_source_ids:
                seen_source_ids.add(source_id)
                verified_sources.append({
                    "id": source_id,
                    "document": source_name,
                    "reference": ref_label,
                    "type": meta.get("type", "pdf"),
                    "title": meta.get("title", ""),
                    "similarity": chunk.get("similarity", 1.0)
                })

    return {
        "answer": cleaned_answer,
        "sources": verified_sources
    }

def generate_answer_with_gemini(prompt: str, context_str: str, query: str) -> Dict[str, Any]:
    """
    Generates structured JSON answers through the Gemini REST API.

    Uses ``requests`` with an explicit timeout instead of the deprecated
    ``google-generativeai`` SDK, which can hang indefinitely with some newer
    model IDs. Falls through several supported model names on errors.
    """
    system_instruction = (
        "You are an expert academic tutor. Answer the student's question using ONLY the provided context.\n"
        "You must return your output strictly in JSON format matching this schema:\n"
        "{\n"
        '  "answer": "Your detailed answer string here, using inline square bracket citations like [1] or [2] at the end of relevant sentences.",\n'
        '  "citations": [1, 2]\n'
        "}\n"
        "Do not return any extra explanation, markdown wrapping, or commentary. Strictly ground every statement."
    )
    full_prompt = f"{system_instruction}\n\nContext:\n{context_str}\n\nQuestion: {query}"

    payload = {
        "contents": [{"role": "user", "parts": [{"text": full_prompt}]}],
        "generationConfig": {
            "temperature": 0.1,
            "responseMimeType": "application/json",
        },
    }

    last_error = None
    for model_name in GEMINI_MODEL_FALLBACKS:
        url = f"https://generativelanguage.googleapis.com/v1beta/models/{model_name}:generateContent"
        try:
            print(f"[Gemini] Trying model {model_name}...")
            start_time = time.time()
            response = requests.post(
                url,
                params={"key": GEMINI_API_KEY},
                json=payload,
                timeout=GEMINI_TIMEOUT_SECONDS,
            )
            latency = time.time() - start_time
            response.raise_for_status()

            data = response.json()
            candidates = data.get("candidates") or []
            if not candidates:
                raise ValueError(data.get("error", {}).get("message", "Gemini returned no candidates."))
            parts = (candidates[0].get("content") or {}).get("parts") or []
            raw_text = "".join(part.get("text", "") for part in parts).strip()
            if not raw_text:
                raise ValueError("Gemini returned an empty response.")

            usage = data.get("usageMetadata") or {}
            tokens = int(
                usage.get("candidatesTokenCount")
                or usage.get("outputTokenCount")
                or 0
            )
            if tokens <= 0:
                tokens = max(1, int(len(raw_text) / 4))
            tokens_per_sec = tokens / latency if latency > 0 else 0.0

            return {
                "text": raw_text,
                "metrics": {
                    "latency_seconds": round(latency, 2),
                    "tokens_generated": tokens,
                    "tokens_per_second": round(tokens_per_sec, 2),
                    "provider": f"gemini ({model_name})",
                },
            }
        except Exception as exc:
            last_error = exc
            print(f"[Gemini] {model_name} unavailable: {exc}")
            continue

    raise last_error or RuntimeError("No Gemini model was available.")

def generate_answer_with_ollama(prompt: str) -> Dict[str, Any]:
    """
    Generates structured JSON answers using local Ollama.
    Captures exact Ollama evaluation benchmarks (latency, token speed).
    """
    url = f"{OLLAMA_HOST}/api/generate"
    payload = {
        "model": OLLAMA_MODEL,
        "prompt": prompt,
        "format": "json",  # Force deterministic JSON structure
        "stream": False,
        "options": {
            "temperature": 0.0  # Zero temperature for maximum grounding determinism
        }
    }
    
    try:
        start_time = time.time()
        response = requests.post(url, json=payload, timeout=50)
        latency = time.time() - start_time
        
        response.raise_for_status()
        result = response.json()
        
        raw_text = result.get("response", "").strip()
        
        # Read exact Ollama benchmarking counters
        eval_count = result.get("eval_count", 0)  # Number of tokens generated
        eval_duration_ns = result.get("eval_duration", 1)  # Time spent generating in nanoseconds
        tokens_per_sec = eval_count / (eval_duration_ns / 1e9) if eval_duration_ns > 0 else 0.0
        
        # Fallback to estimation if Ollama didn't return eval count
        if eval_count == 0:
            eval_count = max(1, int(len(raw_text) / 4))
            tokens_per_sec = eval_count / latency if latency > 0 else 0.0
            
        return {
            "text": raw_text,
            "metrics": {
                "latency_seconds": round(latency, 2),
                "tokens_generated": eval_count,
                "tokens_per_second": round(tokens_per_sec, 2),
                "provider": f"ollama ({OLLAMA_MODEL})"
            }
        }
    except requests.exceptions.RequestException as e:
        print(f"Ollama request failed: {e}")
        raise ConnectionError(
            f"Failed to connect to local Ollama server at {OLLAMA_HOST}. "
            "Please ensure Ollama is active, or configure GEMINI_API_KEY in backend/.env."
        )

@observe(name="generate_answer")
def generate_answer(query: str, retrieved_chunks: List[Dict[str, Any]]) -> Dict[str, Any]:
    """
    Executes advanced RAG generation enforcing JSON schemas, running
    telemetry benchmarks, and protecting execution with a 3-attempt backoff retry loop.
    """
    if not retrieved_chunks:
        return {
            "answer": "I couldn't find any relevant sections in your uploaded study materials. Please upload a document first or ask a question about your uploaded materials.",
            "sources": [],
            "metrics": {
                "latency_seconds": 0.0,
                "tokens_generated": 0,
                "tokens_per_second": 0.0,
                "provider": "none"
            }
        }
        
    # Format the context block with a 1-based index
    context_elements = []
    for idx, chunk in enumerate(retrieved_chunks, start=1):
        meta = chunk.get("metadata", {})
        source_name = meta.get("source", "Unknown Document")
        ref_label = f"Page {meta.get('page_number', 'unknown')}" if meta.get('type') == 'pdf' else f"Slide {meta.get('slide_number', 'unknown')}"
        context_elements.append(
            f"--- Source [{idx}] Document: {source_name} ({ref_label}) ---\n{chunk['text']}"
        )
            
    context_str = "\n\n".join(context_elements)
    
    # Construct structured prompt
    prompt = (
        "You are an expert academic tutor. Answer the student's question using ONLY the provided context "
        "from their uploaded study materials. Ground every single statement. Do not use external knowledge.\n\n"
        "OUTPUT FORMAT RULE:\n"
        "You MUST return your output strictly in JSON format matching this schema:\n"
        "{\n"
        '  "answer": "Detailed tutor response here. At the end of every sentence or statement that uses information from a source, you MUST append an inline citation in square brackets using the source index (e.g. [1] or [2] or [3]).",\n'
        '  "citations": [1, 2]\n'
        "}\n\n"
        "Do not return any extra characters outside this JSON block. Do not wrap it in markdown code fences.\n\n"
        f"Context:\n{context_str}\n\n"
        f"Question: {query}\n\n"
        "Deterministic JSON Output:"
    )
    
    max_retries = 3
    retry_delay = 1.0
    last_error = ""
    
    # 🔁 Exponential Backoff Retry Loop
    for attempt in range(1, max_retries + 1):
        try:
            if GEMINI_API_KEY:
                try:
                    print(f"[Attempt {attempt}/{max_retries}] Generating answer using Google Gemini API...")
                    gen_data = generate_answer_with_gemini(prompt, context_str, query)
                except Exception as gemini_err:
                    print(f"[Warning] Gemini API failed: {gemini_err}. Falling back to Ollama ({OLLAMA_MODEL})...")
                    gen_data = generate_answer_with_ollama(prompt)
            else:
                print(f"[Attempt {attempt}/{max_retries}] Generating answer using Ollama ({OLLAMA_MODEL})...")
                gen_data = generate_answer_with_ollama(prompt)
                
            raw_text = gen_data["text"]
            metrics = gen_data["metrics"]
            
            # Clean possible markdown wrapping if the model ignored instructions
            raw_text = re.sub(r'^```json\s*', '', raw_text)
            raw_text = re.sub(r'\s*```$', '', raw_text)
            raw_text = raw_text.strip()
            
            # Deterministic parsing check
            parsed_json = json.loads(raw_text)
            
            # Validate required schema keys
            if "answer" not in parsed_json or "citations" not in parsed_json:
                raise ValueError("JSON schema missing 'answer' or 'citations' keys.")
                
            answer_text = parsed_json["answer"]
            citations_list = parsed_json["citations"]
            
            # Check for standard grounding failure answers
            if "I couldn't find the answer" in answer_text:
                return {
                    "answer": "I couldn't find the answer to this question in the uploaded study materials.",
                    "sources": [],
                    "metrics": metrics
                }
                
            # Verify and filter citations
            verified_results = verify_and_clean_citations(answer_text, citations_list, retrieved_chunks)
            verified_results["metrics"] = metrics
            
            return verified_results
            
        except Exception as e:
            last_error = str(e)
            print(f"[Attempt {attempt} Failed] Reason: {last_error}")
            if attempt < max_retries:
                # Apply exponential backoff delay
                sleep_time = retry_delay * (1.5 ** (attempt - 1))
                print(f"Retrying in {sleep_time:.2f} seconds...")
                time.sleep(sleep_time)
                
    # Fallback response if all retries exhausted
    # Give a user-friendly setup message if no LLM provider could be reached
    _no_provider = (
        not GEMINI_API_KEY and
        ("ConnectionError" in last_error or "Failed to connect" in last_error or "Connection refused" in last_error)
    )
    if _no_provider:
        answer_msg = (
            "⚠️ **No AI Language Model Configured**\n\n"
            "Your documents were indexed successfully, but no language model is available to generate an answer.\n\n"
            "**To fix this, choose one option:**\n\n"
            "**Option 1 — Google Gemini (Cloud, recommended):**\n"
            "1. Get a free API key at https://aistudio.google.com/app/apikey\n"
            "2. Open the `.env` file in the project root\n"
            "3. Set `GEMINI_API_KEY=AIza...your-key-here...`\n"
            "4. Restart the backend server\n\n"
            "**Option 2 — Ollama (Local, offline):**\n"
            "1. Install Ollama from https://ollama.com\n"
            "2. Run: `ollama pull llama3`\n"
            "3. Start Ollama (it runs on port 11434 by default)\n"
            "4. Restart the backend server"
        )
    else:
        answer_msg = (
            f"⚠️ **Answer Generation Failed**\n\n"
            f"The system tried {max_retries} times but could not generate an answer.\n\n"
            f"*Error details: {last_error}*\n\n"
            "Please check that `GEMINI_API_KEY` in `.env` is valid (and optionally set `GEMINI_MODEL`), "
            "or that Ollama is running on port 11434."
        )
    return {
        "answer": answer_msg,
        "sources": [],
        "metrics": {
            "latency_seconds": 0.0,
            "tokens_generated": 0,
            "tokens_per_second": 0.0,
            "provider": "error"
        }
    }
